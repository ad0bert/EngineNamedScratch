/**
 * The test asset is a striped tube (307 vertices) on a chain of four bones with three animations ("bend": linear
 * rotations, "twist": rotations and a step translation, "pulse": a cubic spline scale), generated by
 * {@code tools/gen_tube.py} as {@code models/tube.glb} and {@code gltf/tube.gltf} (same content, embedded data).
 */
class GltfTest {
  private static byte[] bytes(String path) throws IOException {
    try (var in = GltfTest.class.getClassLoader().getResourceAsStream(path)) {
      return in.readAllBytes();
    }
  }

  private static GltfLoader.Asset load(String path) throws IOException {
    return GltfLoader.load(bytes(path), path, uri -> null);
  }

  @Test
  void textAndBinaryFormsReadTheSame() throws IOException {
    final var gltf = load("gltf/tube.gltf");
    final var glb = load("models/tube.glb");
    for (var a : new GltfLoader.Asset[] { gltf, glb }) {
      assertEquals(6, a.nodes().size());
      assertArrayEquals(new int[] { 0 }, a.roots());
      assertEquals("bone1", a.nodes().get(3).name());
      assertEquals(2, a.nodes().get(3).parent());
      assertEquals(new Vector3f(0f, 0.5f, 0f), a.nodes().get(3).translation());
      final var mesh = a.meshes().get(0).primitives().get(0).mesh();
      assertEquals(307, mesh.vertexCount());
      assertEquals(528 * 3, mesh.indices().length);
      assertTrue(mesh.isSkinned());
      assertEquals(1, a.skins().size());
      assertArrayEquals(new int[] { 2, 3, 4, 5 }, a.skins().get(0).joints());
      assertEquals(-1.5f, a.skins().get(0).inverseBind()[3].m31(), 1e-6f);
      assertEquals(3, a.animations().size());
    }
    assertArrayEquals(gltf.meshes().get(0).primitives().get(0).mesh().vertices(),
        glb.meshes().get(0).primitives().get(0).mesh().vertices());
  }

  @Test
  void verticesMaterialsAndImages() throws IOException {
    final var a = load("models/tube.glb");
    final var mesh = a.meshes().get(0).primitives().get(0).mesh();
    final float[] v = mesh.vertices();
    assertEquals(0.25f, v[0], 1e-6f); // first vertex: radius 0.25 on +X at the bottom
    assertEquals(0f, v[1], 1e-6f);
    assertEquals(1f, v[3], 1e-6f); // normal +X
    assertEquals(0f, v[7], 1e-6f); // glTF v = 1 at the bottom, flipped to the engine's 0
    final float[] skin = mesh.skin();
    assertEquals(1f, skin[4] + skin[5] + skin[6] + skin[7], 1e-6f);
    final int top = 16 * 17; // the first vertex of the top row: all on bone 3 (indices 2 and 3, weights 0 and 1)
    assertEquals(3f, skin[top * MeshData.SKIN_FLOATS_PER_VERTEX + 1]);
    assertEquals(1f, skin[top * MeshData.SKIN_FLOATS_PER_VERTEX + 5], 1e-6f);

    final var m = a.materials().get(0);
    assertEquals("stripes", m.name());
    assertEquals(0f, m.metallic());
    assertEquals(0.45f, m.roughness(), 1e-6f);
    assertEquals(0, m.baseColorTexture().image());
    assertNull(m.normalTexture());
    final var img = a.images().get(0);
    assertEquals(8, img.width());
    // bottom-up rows: the first row is the image's last (odd, teal) stripe
    assertEquals(40, img.rgba()[0] & 0xFF);
    assertEquals(170, img.rgba()[1] & 0xFF);
    assertEquals(235, img.rgba()[img.width() * 4 * 7] & 0xFF);
  }

  @Test
  void animationsSampleAllThreeInterpolations() throws IOException {
    final var a = load("gltf/tube.gltf");
    final var bend = a.animations().get(0);
    assertEquals("bend", bend.name());
    assertEquals(4f, bend.duration(), 1e-6f);
    final var ch = bend.channels().get(0);
    assertEquals("bone1", ch.node());
    assertEquals(Channel.Property.ROTATION, ch.property());
    final float[] out = new float[4];
    ch.track().sample(1f, out, true);
    final var expected = new Quaternionf().rotateZ((float) Math.toRadians(28));
    assertEquals(1f, Math.abs(new Quaternionf(out[0], out[1], out[2], out[3]).dot(expected)), 1e-5f);
    ch.track().sample(0.5f, out, true); // slerped halfway
    assertEquals(1f, Math.abs(new Quaternionf(out[0], out[1], out[2], out[3])
        .dot(new Quaternionf().rotateZ((float) Math.toRadians(14)))), 1e-5f);

    final var step = a.animations().get(1).channels().get(3);
    assertEquals(Channel.Property.POSITION, step.property());
    step.track().sample(0.99f, out, false);
    assertEquals(0f, out[1]);
    step.track().sample(1f, out, false);
    assertEquals(0.15f, out[1], 1e-6f);

    final var pulse = a.animations().get(2).channels().get(0);
    pulse.track().sample(0.25f, out, false); // zero tangents: halfway in time is halfway in value
    assertEquals(1.3f, out[0], 1e-5f);
    pulse.track().sample(0.5f, out, false);
    assertEquals(1.6f, out[0], 1e-5f);
  }

  @Test
  void instancesAreSkinnedAndAnimated() {
    final var res = new ResourceManager(new ResourceTest.FakeBackend());
    final var model = res.gltf("models/tube.glb");
    assertSame(model, res.gltf("models/tube.glb"));
    final var scene = new Scene();
    final var root = model.instantiate(scene);
    scene.flush();
    assertEquals("tube-root", root.name());
    assertEquals(6, scene.entities().size());
    final Entity tube = scene.entities().stream().filter(e -> e.name().equals("tube-mesh")).findFirst().get();
    final var renderer = tube.get(MeshRenderer.class);
    assertNotNull(renderer.skin);
    assertEquals(4, renderer.skin.jointCount());
    assertTrue(renderer.material.pbr);
    assertNotNull(renderer.material.texture);
    assertEquals("models/tube.glb#mesh0.0", res.keyOf(renderer.mesh));
    assertSame(renderer.mesh, res.meshByKey("models/tube.glb#mesh0.0"));
    assertTrue(model.model().parts().isEmpty()); // its only mesh is skinned

    // bind pose: every joint matrix is the identity
    final var world = tube.transform().worldMatrix(new Matrix4f());
    renderer.skin.update(1, 1f, world);
    final float[] palette = renderer.skin.palette();
    for (int j = 0; j < 4; j++) {
      assertTrue(new Matrix4f().set(palette, j * 16).equals(new Matrix4f(), 1e-5f), "joint " + j);
    }

    // bent for a second: the top of the tube leans towards -x, and the GPU formula matches the bone's own motion
    final var animator = root.get(Animator.class);
    assertEquals(3, animator.clips().size());
    animator.play("bend", AnimationLayer.Loop.LOOP);
    final var system = new AnimationSystem();
    system.animate(scene, animator, 1f);
    for (Entity e : scene.entities()) {
      e.transform().snapshot();
    }
    renderer.skin.update(2, 1f, tube.transform().worldMatrix(new Matrix4f()));
    final var top = new Vector4f(0f, 2f, 0f, 1f); // the cap centre, weighted fully to bone 3
    new Matrix4f().set(palette, 3 * 16).transform(top);
    assertTrue(top.x < -0.5f, "top x " + top.x);
    final Entity bone3 = scene.entities().stream().filter(e -> e.name().equals("bone3")).findFirst().get();
    final var tip = bone3.transform().worldMatrix(new Matrix4f()).transformPosition(new Vector3f(0f, 0.5f, 0f));
    assertEquals(tip.x, top.x, 1e-4f);
    assertEquals(tip.y, top.y, 1e-4f);
  }

  @Test
  void brokenFilesFail() {
    assertThrows(IOException.class, () -> GltfLoader.load("{\"asset\": {\"version\": \"1.0\"}}".getBytes(), "old",
        uri -> null));
    assertThrows(IOException.class, () -> GltfLoader.load("not json".getBytes(), "junk", uri -> null));
    assertThrows(IllegalStateException.class, () -> new ResourceManager(new ResourceTest.FakeBackend())
        .gltf("models/missing.glb"));
  }
}
